    #region Helpers

    private enum EffectiveRequirement
    {
        Required,
        Optional,
    }

    private static EffectiveRequirement ResolveRequirement(BindingMember m)
    {
        // Explicit attribute
        if (m.Requirement == EnvRequirement.Required)
        {
            return EffectiveRequirement.Required;
        }

        // Explicit attribute
        if (m.Requirement == EnvRequirement.Optional)
        {
            return EffectiveRequirement.Optional;
        }

        // Inferred path:
        if (m.HasRequiredKeyword)
        {
            return EffectiveRequirement.Required;
        }

        if (m.CSharpInitializerExpression is not null)
        {
            return EffectiveRequirement.Optional;
        }

        if (m.TypeIsNullable)
        {
            return EffectiveRequirement.Optional;
        }

        return EffectiveRequirement.Required;
    }

    private static string StorageTypeOf(BindingMember m)
    {
        // For optional members we want the storage to be nullable so the
        // default-fallback path can leave it untouched. For required we use
        // the declared type as-is.
        var declared = m.TypeFullyQualifiedName;
        return ResolveRequirement(m) switch
        {
            EffectiveRequirement.Required => declared,
            _ => m.TypeIsNullable ? declared : declared + "?",
        };
    }

    private static BindingMember? TryFindMember(BindingTarget target, string memberName)
    {
        foreach (var m in target.Members.AsImmutableArray())
        {
            if (m.MemberName == memberName)
            {
                return m;
            }
        }
        return null;
    }

