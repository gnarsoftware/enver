    #region Helpers

    private enum EffectiveRequirement
    {
        Required,
        Optional,
    }

    private static EffectiveRequirement ResolveRequirement(BindingMember m) =>
        ResolveRequirement(
            m.Requirement,
            m.HasRequiredKeyword,
            m.CSharpInitializerExpression,
            m.TypeIsNullable
        );

    private static EffectiveRequirement ResolveRequirement(SubSection s) =>
        ResolveRequirement(
            s.Requirement,
            s.HasRequiredKeyword,
            s.CSharpInitializerExpression,
            s.TypeIsNullable
        );

    private static EffectiveRequirement ResolveRequirement(PolymorphicMember p) =>
        ResolveRequirement(
            p.Requirement,
            p.HasRequiredKeyword,
            p.CSharpInitializerExpression,
            p.TypeIsNullable
        );

    private static EffectiveRequirement ResolveRequirement(
        EnvRequirement requirement,
        bool hasRequiredKeyword,
        string? initializer,
        bool typeIsNullable
    )
    {
        // Explicit attribute
        if (requirement == EnvRequirement.Required)
        {
            return EffectiveRequirement.Required;
        }

        // Explicit attribute
        if (requirement == EnvRequirement.Optional)
        {
            return EffectiveRequirement.Optional;
        }

        // Inferred path:
        if (hasRequiredKeyword)
        {
            return EffectiveRequirement.Required;
        }

        if (initializer is not null)
        {
            return EffectiveRequirement.Optional;
        }

        if (typeIsNullable)
        {
            return EffectiveRequirement.Optional;
        }

        return EffectiveRequirement.Required;
    }

    /// <summary>
    /// A member name as a C# identifier. A property declared as <c>@event</c> has
    /// the name <c>event</c>, which only compiles with its <c>@</c> back.
    /// </summary>
    private static string Id(string name) =>
        Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name)
        != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None
            ? "@" + name
            : name;

    private static string StorageTypeOf(BindingMember m)
    {
        // For optional members we want the storage to be nullable so the
        // default-fallback path can leave it untouched. For required we use
        // the declared type as-is.
        var declared = m.TypeFullyQualifiedName;
        return ResolveRequirement(m) switch
        {
            EffectiveRequirement.Required => declared,
            _ => m.TypeIsNullable ? declared : declared + "?",
        };
    }

    private static BindingMember? TryFindMember(BindingTarget target, string memberName)
    {
        foreach (var m in target.Members.AsImmutableArray())
        {
            if (m.MemberName == memberName)
            {
                return m;
            }
        }
        return null;
    }

