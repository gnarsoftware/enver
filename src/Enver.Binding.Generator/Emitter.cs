using System.CodeDom.Compiler;
using System.Text;
using Enver.Binding.Generator.Model;

namespace Enver.Binding.Generator;

internal static partial class Emitter
{
    public static string Emit(BindingHost host)
    {
        using var sw = new StringWriter();
        using var w = new IndentedTextWriter(sw);

        w.WriteLine("// <auto-generated/>");
        w.WriteLine("#nullable enable");
        w.WriteLine("#pragma warning disable CS8601 // Possible null reference assignment");
        w.WriteLine(
            "#pragma warning disable CS8618 // Non-nullable field must contain a non-null value when exiting constructor"
        );
        w.WriteLine(
            "#pragma warning disable CS1591 // Missing XML comment for publicly visible type or member"
        );
        // A bindable type deriving from another bindable type gets its own Bind,
        // Binder, EnvKeys and so on, which deliberately hide the base type's.
        w.WriteLine(
            "#pragma warning disable CS0108 // Member hides inherited member; missing new keyword"
        );
        w.WriteLine();

        if (host.HostNamespace.Length > 0)
        {
            w.WriteLine($"namespace {host.HostNamespace};");
            w.WriteLine();
        }

        // Open the enclosing type chain.
        int enclosingDepth = 0;
        foreach (var enc in host.EnclosingTypes.AsImmutableArray())
        {
            w.WriteLine($"partial {enc.Keyword} {enc.Name}");
            w.WriteLine("{");
            w.Indent++;
            enclosingDepth++;
        }

        // Open the host partial. A public self-bound type implements IEnvBinding<T>
        // itself; everything else gets a nested binding class (EmitBindingClass).
        var implementsBinding = ImplementsBindingInterface(host);
        w.WriteLine(
            implementsBinding
                ? $"partial {host.HostKeyword} {host.HostName} : {BindingInterface(host.Target)}"
                : $"partial {host.HostKeyword} {host.HostName}"
        );
        w.WriteLine("{");
        w.Indent++;

        // Self-bind hosts get the plain Bind/Binder names; external hosts
        // ([EnvBindable<T>]) suffix them with the target's simple name.
        var target = host.Target;
        var methodInfix = host.HostIsSelfBindable ? "" : target.SimpleTypeName;
        var binderName = host.HostIsSelfBindable ? "Binder" : $"{target.SimpleTypeName}Binder";
        var access = host.Accessibility;
        EmitStaticMethods(w, target, methodInfix, binderName, access);
        w.WriteLine();
        EmitBinderClass(w, target, binderName, methodInfix, access);
        if (host.GenerateKeys)
        {
            EmitKeyClasses(w, host, access);
        }
        w.WriteLine();
        if (implementsBinding)
        {
            EmitBindingMembers(w, target, methodInfix);
        }
        else
        {
            EmitBindingClass(w, host, methodInfix, access);
        }
        EmitValidateHelpers(w, target);
        EmitPolymorphicHelpers(w, target);

        // Close host partial + enclosing types.
        w.Indent--;
        w.WriteLine("}");
        for (int i = 0; i < enclosingDepth; i++)
        {
            w.Indent--;
            w.WriteLine("}");
        }

        return sw.ToString();
    }

    #region Static helper methods

    private static void EmitStaticMethods(
        IndentedTextWriter w,
        BindingTarget target,
        string methodInfix,
        string binderName,
        string access
    )
    {
        var t = target.FullyQualifiedTypeName;

        // The validate parameter and Validate method exist only when something in
        // the tree has rules to check.
        var validates = HasValidation(target);
        var validateParam = validates ? ", bool validate = true" : "";
        var buildArgs = validates ? "validate" : "";

        // Bind(IEnvReader)
        w.WriteLine(
            validates
                ? "/// <summary>Bind a fresh instance from an existing reader, then validate it "
                    + $"unless <paramref name=\"validate\"/> is false (see <c>Validate{methodInfix}</c>).</summary>"
                : "/// <summary>Bind a fresh instance from an existing reader.</summary>"
        );
        w.WriteLine(
            $"{access} static {t} Bind{methodInfix}(global::Enver.IEnvReader reader{validateParam})"
        );
        w.WriteLine("{");
        w.Indent++;
        if (target.Self is { } self)
        {
            w.WriteLine($"var __result = {self.HelperName}(reader);");
        }
        else
        {
            w.Write("var __result = ");
            EmitInlineObjectConstructionForReader(w, target);
            w.WriteLine(";");
        }
        if (validates)
        {
            w.WriteLine($"if (validate) Validate{methodInfix}(__result);");
        }
        w.WriteLine("return __result;");
        w.Indent--;
        w.WriteLine("}");
        w.WriteLine();

        // Bind(string path)
        w.WriteLine(
            "/// <summary>Bind a fresh instance by loading the given .env file. "
                + "Missing files are silently skipped.</summary>"
        );
        w.WriteLine(
            $"{access} static {t} Bind{methodInfix}("
                + "string path, "
                + "global::Enver.Parsing.EnvParseOptions parseOptions = default"
                + validateParam
                + ")"
        );
        w.WriteLine("{");
        w.Indent++;
        w.WriteLine($"var binder = new {binderName}();");
        w.WriteLine("global::Enver.Loading.EnvFileLoader.Load(binder, path, parseOptions);");
        w.WriteLine($"return binder.Build({buildArgs});");
        w.Indent--;
        w.WriteLine("}");
        w.WriteLine();

        // Bind(IEnumerable<string> paths)
        w.WriteLine(
            "/// <summary>Bind a fresh instance by loading each .env file in order; "
                + "later files override values defined in earlier ones, with shared "
                + "<c>${VAR}</c> interpolation across the whole sequence. Missing files are "
                + "silently skipped. Pair with <see cref=\"global::Enver.DotEnvPaths\"/> "
                + "to compose the canonical ladder.</summary>"
        );
        w.WriteLine(
            $"{access} static {t} Bind{methodInfix}("
                + "global::System.Collections.Generic.IEnumerable<string> paths, "
                + "global::Enver.Parsing.EnvParseOptions parseOptions = default"
                + validateParam
                + ")"
        );
        w.WriteLine("{");
        w.Indent++;
        w.WriteLine($"var binder = new {binderName}();");
        w.WriteLine("global::Enver.Loading.EnvFileLoader.Load(binder, paths, parseOptions);");
        w.WriteLine($"return binder.Build({buildArgs});");
        w.Indent--;
        w.WriteLine("}");
        if (validates)
        {
            w.WriteLine();
            EmitPublicValidateMethod(w, target, methodInfix, access);
        }

        if (target.GeneratePopulate)
        {
            w.WriteLine();
            EmitPopulateStaticMethod(w, target, methodInfix, access);
        }
    }

    private static void EmitInlineObjectConstructionForReader(
        IndentedTextWriter w,
        BindingTarget target
    )
    {
        w.Write($"new {target.FullyQualifiedTypeName}(");
        var ctorNames = target.Construction.CtorParameterMemberNames.AsImmutableArray();
        for (int i = 0; i < ctorNames.Length; i++)
        {
            if (i > 0)
            {
                w.Write(", ");
            }

            var memberName = ctorNames[i];
            w.Write($"{Id(memberName)}: ");
            EmitInlineMemberInitializationForReader(w, target, memberName);
        }
        w.Write(")");

        var initNames = target.Construction.ObjectInitializerMemberNames.AsImmutableArray();
        if (initNames.Length != 0)
        {
            w.WriteLine();
            w.WriteLine("{");
            w.Indent++;
            foreach (var memberName in initNames)
            {
                w.Write($"{Id(memberName)} = ");
                EmitInlineMemberInitializationForReader(w, target, memberName);
                w.WriteLine(",");
            }
            w.Indent--;
            w.Write("}");
        }
    }

    private static void EmitInlineMemberInitializationForReader(
        IndentedTextWriter w,
        BindingTarget target,
        string memberName
    )
    {
        var member = TryFindMember(target, memberName);
        if (member is not null)
        {
            EmitInlineCallExpressionForReader(w, member, target);
        }
        else
        {
            foreach (var sub in target.SubSections.AsImmutableArray())
            {
                if (sub.MemberName == memberName)
                {
                    EmitSubSectionForReader(w, sub);
                    return;
                }
            }
            if (TryFindPolymorphic(target, memberName) is { } poly)
            {
                w.Write(PolymorphicExpression(poly, "reader"));
                return;
            }
            throw new InvalidOperationException(
                $"SubSection '{memberName}' not found in target '{target.SimpleTypeName}'."
            );
        }
    }

    /// <summary>
    /// A required subsection is always constructed. An optional one is constructed
    /// only when at least one key in its subtree is present; otherwise it takes its
    /// initializer (or null).
    /// </summary>
    private static void EmitSubSectionForReader(IndentedTextWriter w, SubSection sub)
    {
        if (ResolveRequirement(sub) is EffectiveRequirement.Required)
        {
            EmitInlineObjectConstructionForReader(w, sub.Target);
            return;
        }

        var keys = new List<string>();
        CollectPresenceKeys(sub.Target, keys);
        var present = string.Join(" || ", keys.Select(k => $"reader.TryGetValue(\"{k}\", out _)"));
        w.Write($"(({present}) ? ({sub.TypeFullyQualifiedName})");
        EmitInlineObjectConstructionForReader(w, sub.Target);
        w.Write($" : {sub.CSharpInitializerExpression ?? "default!"})");
    }

    /// <summary>
    /// Keys whose presence means "this subsection was configured": every leaf key in
    /// the subtree, plus each polymorphic member's type key (or scalar value key).
    /// </summary>
    private static void CollectPresenceKeys(BindingTarget target, List<string> keys)
    {
        foreach (var m in target.Members.AsImmutableArray())
        {
            keys.AddRange(m.AllKeys());
        }
        foreach (var sub in target.SubSections.AsImmutableArray())
        {
            CollectPresenceKeys(sub.Target, keys);
        }
        foreach (var poly in target.Polymorphics.AsImmutableArray())
        {
            keys.Add(poly.Key);
        }
    }

    private static void EmitInlineCallExpressionForReader(
        IndentedTextWriter w,
        BindingMember m,
        BindingTarget target
    )
    {
        var isOptional = ResolveRequirement(m) is EffectiveRequirement.Optional;

        w.Write("global::Enver.EnvReaderExtensions.Get");
        if (isOptional)
        {
            w.Write("Optional");
        }

        w.Write(ReaderMethod(m, isOptional));
        w.Write($"(reader, {ReaderKeyExpression(m, isOptional)}");
        if (m.Dispatch == TypeDispatchKind.Uri)
        {
            w.Write(", ");
            w.Write(UriKindExpression(m));
        }
        if (TypeDispatch.UsesFormatProvider(m.Dispatch))
        {
            w.Write(", ");
            var fp = m.FormatProvider ?? target.DefaultFormatProvider;
            w.Write(
                fp is null
                    ? "default(global::System.IFormatProvider)"
                    : $"{fp.TypeFullyQualifiedName}.{Id(fp.MemberName)}"
            );
        }
        w.Write(")");

        // GetOptional* returns T?. When the target member is non-nullable (an
        // optional value type) or declares a C# initializer, fall back to the
        // declared default so the result is the member's type and the default
        // is honored.
        if (isOptional && (m.CSharpInitializerExpression is not null || !m.TypeIsNullable))
        {
            w.Write($" ?? {m.CSharpInitializerExpression ?? "default"}");
        }
    }

    /// <summary>
    /// The key to read: the primary key when there are no fallbacks, otherwise the
    /// first key in the chain that is present. When none is, an optional member
    /// reads the (missing) primary key and gets its default; a required one throws
    /// naming every key tried.
    /// </summary>
    private static string ReaderKeyExpression(BindingMember m, bool isOptional)
    {
        if (m.FallbackKeys.Length == 0)
        {
            return $"\"{m.ResolvedKey}\"";
        }
        var sb = new StringBuilder("(");
        foreach (var key in m.AllKeys())
        {
            sb.Append($"reader.TryGetValue(\"{key}\", out _) ? \"{key}\" : ");
        }
        sb.Append(isOptional ? $"\"{m.ResolvedKey}\"" : MissingVariableThrow(m));
        sb.Append(')');
        return sb.ToString();
    }

    /// <summary>
    /// <c>throw new EnvMissingVariableException(...)</c> for a required member,
    /// listing its fallback keys when it has any.
    /// </summary>
    private static string MissingVariableThrow(BindingMember m)
    {
        var message = $"missing required env variable '{m.ResolvedKey}'";
        if (m.FallbackKeys.Length > 0)
        {
            message +=
                " (also tried "
                + string.Join(", ", m.FallbackKeys.AsImmutableArray().Select(k => $"'{k}'"))
                + ")";
        }
        return $"throw new global::Enver.EnvMissingVariableException(\"{m.ResolvedKey}\", \"{message}\")";
    }

    private static string ReaderMethod(BindingMember m, bool isOptional)
    {
        return m.Dispatch switch
        {
            TypeDispatchKind.String => "String",
            TypeDispatchKind.Boolean => "Boolean",
            TypeDispatchKind.Guid => "Guid",
            TypeDispatchKind.Uri => "Uri",
            TypeDispatchKind.Version => "Version",
            TypeDispatchKind.Enum => $"Enum<{m.UnderlyingTypeFullyQualifiedName}>",
            TypeDispatchKind.Number => $"Number<{m.UnderlyingTypeFullyQualifiedName}>",
            // char and any IUtf8SpanParsable / ISpanParsable / IParsable type
            // bind through the generic Get<T> entry point.
            TypeDispatchKind.Utf8SpanParsable
            or TypeDispatchKind.SpanParsable
            or TypeDispatchKind.Parsable =>
                $"{(isOptional && !m.UnderlyingIsValueType ? "Ref" : "")}<{m.UnderlyingTypeFullyQualifiedName}>",
            _ => throw new InvalidOperationException(), // Unsupported is filtered before emit
        };
    }

    private static string UriKindExpression(BindingMember m) =>
        $"global::System.UriKind.{m.UriKind ?? UriKind.Absolute}";

    private static string? FormatProviderExpression(BindingMember m, BindingTarget target)
    {
        if (!TypeDispatch.UsesFormatProvider(m.Dispatch))
        {
            return null;
        }
        var fp = m.FormatProvider ?? target.DefaultFormatProvider;
        return fp is null ? null : $"{fp.TypeFullyQualifiedName}.{Id(fp.MemberName)}";
    }

